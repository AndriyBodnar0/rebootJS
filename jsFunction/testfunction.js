// Функція для конвертації числа з однієї системи числення в іншу
function convert(number, base_in, base_out) {
    if (base_in == 10) {
      // Конвертуємо з десяткової системи числення
      var result = "";
      while (number > 0) {
        var remainder = number % base_out;
        if (remainder < 10) {
          result = remainder.toString() + result;
        } else {
          result = String.fromCharCode('A'.charCodeAt(0) + remainder - 10) + result;
        }
        number = Math.floor(number / base_out);
      }
      return result;
    } else {
      // Конвертуємо в десяткову систему числення
      var decimal = 0;
      var number_str = number.toString();
      for (var i = 0; i < number_str.length; i++) {
        var digit = number_str.charAt(i);
        if (digit >= '0' && digit <= '9') {
          decimal = decimal * base_in + parseInt(digit);
        } else {
          decimal = decimal * base_in + digit.charCodeAt(0) - 'A'.charCodeAt(0) + 10;
        }
      }
      // Конвертуємо з десяткової системи числення в вибрану користувачем
      return convert(decimal, 10, base_out);
    }
  }
  
  // Зчитуємо введені користувачем дані
  var number = prompt("Введіть число:");
  var base_in = parseInt(prompt("Введіть початкову систему числення (2-36):"));
  var base_out = parseInt(prompt("Введіть систему числення, у яку потрібно конвертувати (2-36):"));
  
  // Конвертуємо число в вибрану користувачем систему числення та виводимо результат
  var result = convert(parseInt(number, base_in), 10, base_out);
